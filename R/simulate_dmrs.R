.prepareSimulationPheno <- function(samplesheet,
                                    samplesheet_sep,
                                    sample_names,
                                    sample_groups,
                                    sample_group_col) {
    if (length(sample_group_col) != 1L || is.na(sample_group_col) || !nzchar(sample_group_col)) {
        stop("'sample_group_col' must be a non-empty character scalar.")
    }

    if (is.null(samplesheet)) {
        pheno <- stats::setNames(
            data.frame(sample_groups, stringsAsFactors = FALSE),
            sample_group_col
        )
        rownames(pheno) <- sample_names
        return(pheno)
    }

    if (is.character(samplesheet) && length(samplesheet) == 1L) {
        pheno <- utils::read.table(
            samplesheet,
            header = TRUE,
            stringsAsFactors = FALSE,
            sep = samplesheet_sep,
            check.names = FALSE
        )
        if (ncol(pheno) > 0L && colnames(pheno)[[1L]] == "") {
            rownames(pheno) <- as.character(pheno[[1L]])
            pheno <- pheno[, -1L, drop = FALSE]
        }
    } else if (is.data.frame(samplesheet)) {
        pheno <- as.data.frame(samplesheet)
    } else {
        stop("'samplesheet' must be NULL, a file path, or a data frame.")
    }

    colnames(pheno) <- trimws(colnames(pheno))
    if (.simulationHasDefaultRowNames(pheno) && "Sample_ID" %in% colnames(pheno)) {
        rownames(pheno) <- as.character(pheno$Sample_ID)
    }
    if (.simulationHasDefaultRowNames(pheno)) {
        stop("'samplesheet' must have sample row names or a 'Sample_ID' column.")
    }
    if (anyNA(rownames(pheno)) || any(!nzchar(rownames(pheno)))) {
        stop("'samplesheet' row names must be non-empty sample names.")
    }
    if (anyDuplicated(rownames(pheno)) > 0L) {
        stop("'samplesheet' sample names must be unique.")
    }

    missing_samples <- setdiff(sample_names, rownames(pheno))
    if (length(missing_samples) > 0L) {
        stop(
            "The following input samples are missing from samplesheet: ",
            paste(head(missing_samples, 10), collapse = ", "),
            if (length(missing_samples) > 10L) " ..." else ""
        )
    }

    pheno <- pheno[sample_names, , drop = FALSE]
    pheno[[sample_group_col]] <- sample_groups
    pheno
}

.simulationHasDefaultRowNames <- function(x) {
    identical(rownames(x), as.character(seq_len(nrow(x))))
}

.normalizeSimulationCovariates <- function(covariates) {
    if (is.null(covariates)) {
        return(NULL)
    }
    if (length(covariates) == 1L && is.character(covariates)) {
        covariates <- unlist(strsplit(covariates, ","))
    }
    covariates <- trimws(as.character(covariates))
    covariates <- covariates[nzchar(covariates)]
    if (length(covariates) == 0L) {
        return(NULL)
    }
    unique(covariates)
}

.residualizeSimulationCounts <- function(meth,
                                         cov,
                                         pheno,
                                         covariates,
                                         sample_group_col) {
    if (is.null(covariates)) {
        return(meth)
    }
    if (is.null(pheno)) {
        stop("'samplesheet' must be provided when 'covariates' are supplied.")
    }
    if (sample_group_col %in% covariates) {
        stop("'covariates' must not include 'sample_group_col'.")
    }
    covariate_model <- .prepareCovariateModel(pheno = pheno, covariates = covariates)
    if (is.null(covariate_model) || isTRUE(covariate_model$is_singular)) {
        return(meth)
    }
    non_intercept <- colnames(covariate_model$covariate_matrix) != "(Intercept)"
    if (!any(non_intercept)) {
        return(meth)
    }
    if (ncol(meth) != nrow(covariate_model$covariate_matrix)) {
        stop("Input samples and covariate rows must have the same length.")
    }

    signal <- .convertCountsToLogits(meth = meth, cov = cov)
    signal[!is.finite(signal)] <- 0
    coef <- t(covariate_model$pseudo_solution %*% t(signal))
    fitted_covariates <- coef[, non_intercept, drop = FALSE] %*%
        t(covariate_model$covariate_matrix[, non_intercept, drop = FALSE])
    residualized_signal <- signal - fitted_covariates
    residualized_signal <- residualized_signal +
        rowMeans(signal, na.rm = TRUE) -
        rowMeans(residualized_signal, na.rm = TRUE)
    residualized_prob <- plogis(residualized_signal)
    residualized_meth <- round(residualized_prob * cov)
    residualized_meth[cov <= 0] <- 0
    residualized_meth[residualized_meth < 0] <- 0
    over_cov <- residualized_meth > cov
    residualized_meth[over_cov] <- cov[over_cov]
    dimnames(residualized_meth) <- dimnames(meth)
    residualized_meth
}

.collapseSimulationDuplicateLoci <- function(meth, cov, chr, pos, end = NULL, row_ids = NULL) {
    key <- paste(chr, pos, sep = "\t")
    duplicate_mask <- duplicated(key)
    if (is.null(end)) {
        end <- pos
    }
    if (is.null(row_ids)) {
        row_ids <- paste0(chr, ":", pos)
    }

    if (!any(duplicate_mask)) {
        return(list(
            meth = meth,
            cov = cov,
            chr = chr,
            pos = pos,
            end = end,
            row_ids = row_ids,
            n_collapsed = 0L
        ))
    }

    first_idx <- match(unique(key), key)
    meth_collapsed <- rowsum(meth, group = key, reorder = FALSE)
    cov_collapsed <- rowsum(cov, group = key, reorder = FALSE)
    colnames(meth_collapsed) <- colnames(meth)
    colnames(cov_collapsed) <- colnames(cov)

    row_ids_collapsed <- as.character(row_ids[first_idx])
    if (anyDuplicated(row_ids_collapsed) > 0L) {
        row_ids_collapsed <- make.unique(row_ids_collapsed)
    }

    list(
        meth = as.matrix(meth_collapsed),
        cov = as.matrix(cov_collapsed),
        chr = chr[first_idx],
        pos = pos[first_idx],
        end = end[first_idx],
        row_ids = row_ids_collapsed,
        n_collapsed = as.integer(sum(duplicate_mask))
    )
}

.orderSimulationLoci <- function(x) {
    ord <- order(x$chr, x$pos, x$end, na.last = TRUE)
    if (identical(ord, seq_along(ord))) {
        return(x)
    }
    x$meth <- x$meth[ord, , drop = FALSE]
    x$cov <- x$cov[ord, , drop = FALSE]
    x$chr <- x$chr[ord]
    x$pos <- x$pos[ord]
    x$end <- x$end[ord]
    x$row_ids <- x$row_ids[ord]
    x
}

.resolveSimulationGroups <- function(groups, n_samples, case_group = NULL) {
    if (is.null(groups)) {
        n_control <- floor(n_samples / 2)
        groups <- c(
            rep("Condition1", n_control),
            rep("Condition2", n_samples - n_control)
        )
    }
    groups <- as.character(groups)
    if (length(groups) != n_samples) {
        stop("'groups' must have length equal to the number of samples.")
    }
    if (anyNA(groups) || any(!nzchar(groups))) {
        stop("'groups' must not contain missing or empty values.")
    }
    group_levels <- unique(groups)
    if (length(group_levels) < 2L) {
        stop("'groups' must contain at least two groups.")
    }
    if (is.null(case_group)) {
        case_group <- group_levels[[2L]]
    }
    case_group <- as.character(case_group)[[1L]]
    if (!case_group %in% group_levels) {
        stop("'case_group' must be one of: ", paste(group_levels, collapse = ", "))
    }
    attr(groups, "case_group") <- case_group
    groups
}

.findContiguousSegments <- function(chr, pos, max_gap) {
    if (length(chr) != length(pos)) {
        stop("'chr' and 'pos' must have the same length.")
    }
    if (length(chr) == 0L) {
        return(integer(0))
    }
    pos_diff <- diff(pos)
    starts <- c(TRUE, chr[-1L] != chr[-length(chr)] | pos_diff < 0L | pos_diff > max_gap)
    cumsum(starts)
}

.simulationEffectProfile <- function(pos, degree, flank_fraction) {
    first <- min(pos)
    last <- max(pos)
    width <- max(last - first, 1)
    first <- first - flank_fraction * width
    last <- last + flank_fraction * width
    width <- max(last - first, 1)
    center <- first + width / 2
    scaled <- abs(pos - center) / (width / 2)
    out <- (1 - pmin(scaled, 1)^degree)^degree
    out[!is.finite(out)] <- 0
    pmax(out, 0)
}

.createCorrelatedEffectPrior <- function(n_sites,
                                         sigma = 0.25,
                                         neighbor_weight = 0.7,
                                         neighbor_window = 5L) {
    if (n_sites <= 1L || !is.finite(sigma) || sigma <= 0) {
        return(rep(0, n_sites))
    }
    if (!is.finite(neighbor_weight)) {
        neighbor_weight <- 0.7
    }
    neighbor_weight <- pmax(neighbor_weight, 0)
    neighbor_window <- as.integer(neighbor_window)
    if (length(neighbor_window) != 1L || is.na(neighbor_window) || neighbor_window < 1L) {
        neighbor_window <- 5L
    }
    neighbor_radius <- min(n_sites - 1L, floor(neighbor_window / 2L))

    site_noise <- stats::rnorm(n_sites)
    latent <- site_noise
    latent_var <- rep(1, n_sites)

    if (neighbor_radius > 0L && neighbor_weight > 0) {
        for (offset in seq_len(neighbor_radius)) {
            weight <- neighbor_weight^offset
            left_idx <- seq.int(offset + 1L, n_sites)
            right_idx <- seq_len(n_sites - offset)
            latent[left_idx] <- latent[left_idx] + weight * site_noise[right_idx]
            latent[right_idx] <- latent[right_idx] + weight * site_noise[left_idx]
            latent_var[left_idx] <- latent_var[left_idx] + weight^2
            latent_var[right_idx] <- latent_var[right_idx] + weight^2
        }
    }
    latent <- latent / sqrt(latent_var)
    as.numeric(sigma * latent)
}

.simulationShiftedProbabilities <- function(base_prob,
                                            diff_hit,
                                            corr_sd = 0,
                                            neighbor_window = 5L) {
    base_prob <- .clampSimulationBeta(base_prob)
    target_prob <- .clampSimulationBeta(base_prob + diff_hit)
    det_shift <- stats::qlogis(target_prob) - stats::qlogis(base_prob)

    correlated_effect <- if (corr_sd > 0) {
        .createCorrelatedEffectPrior(
            n_sites = length(base_prob),
            sigma = corr_sd,
            neighbor_window = neighbor_window
        )
    } else {
        rep(0, length(base_prob))
    }

    plogis(stats::qlogis(base_prob) + det_shift + correlated_effect)
}

.simulationComputePairCorrelations <- function(x, y) {
    if (length(x) == 0L || ncol(x) < 2L || !all(dim(x) == dim(y))) {
        return(numeric(0))
    }
    x_centered <- x - rowMeans(x)
    y_centered <- y - rowMeans(y)
    denom <- sqrt(rowSums(x_centered^2) * rowSums(y_centered^2))
    cors <- rowSums(x_centered * y_centered) / denom
    cors[is.finite(cors)]
}

.simulationBackgroundFitCorrelations <- function(beta, chr, pos, group_indices, max_gap) {
    ord <- order(chr, pos)
    beta_ord <- beta[ord, , drop = FALSE]
    chr_ord <- chr[ord]
    pos_ord <- pos[ord]
    segment_ord <- .findContiguousSegments(chr_ord, pos_ord, max_gap = max_gap)
    pair_end <- which(
        chr_ord[-1L] == chr_ord[-length(chr_ord)] &
            segment_ord[-1L] == segment_ord[-length(segment_ord)]
    ) + 1L
    pair_start <- pair_end - 1L
    if (length(pair_start) == 0L) {
        return(numeric(0))
    }

    pooled <- unlist(lapply(group_indices, function(idx) {
        if (length(idx) < 2L) {
            return(numeric(0))
        }
        m_values <- .transformBeta(
            beta_ord[, idx, drop = FALSE],
            pheno = data.frame(sample = seq_len(length(idx)))
        )
        pair_corr <- .simulationComputePairCorrelations(
            x = m_values[pair_start, , drop = FALSE],
            y = m_values[pair_end, , drop = FALSE]
        )
        pair_corr[pair_corr > 0]
    }))
    pooled[is.finite(pooled)]
}

.simulationFitCorrelationTargets <- function(beta,
                                             chr,
                                             pos,
                                             group_indices,
                                             max_gap,
                                             n_targets,
                                             corr_rate = 1) {
    pos_corr <- .simulationBackgroundFitCorrelations(
        beta = beta,
        chr = chr,
        pos = pos,
        group_indices = group_indices,
        max_gap = max_gap
    )
    if (length(pos_corr) < 20L) {
        return(rep(NA_real_, n_targets))
    }

    corr_mean <- mean(pos_corr)
    corr_var <- stats::var(pos_corr)
    if (!is.finite(corr_mean) || !is.finite(corr_var) || corr_mean <= 0 || corr_var <= 1e-8) {
        return(rep(NA_real_, n_targets))
    }

    shape <- corr_mean^2 / corr_var
    rate <- corr_mean / corr_var
    if (!is.finite(shape) || !is.finite(rate) || shape <= 0 || rate <= 0) {
        return(rep(NA_real_, n_targets))
    }

    pmin(
        pmax(
            stats::rgamma(n = n_targets, shape = shape, rate = rate) * corr_rate,
            0
        ),
        0.99
    )
}

.simulationCorrelationMetric <- function(corr_sd,
                                         affected_samples,
                                         template_length,
                                         template_cov,
                                         neighbor_window = 5L,
                                         pilot_reps = 6L) {
    if (affected_samples < 2L || template_length < 2L || corr_sd <= 0) {
        return(0)
    }

    rep_metrics <- numeric(pilot_reps)
    base_prob <- matrix(0.5, nrow = template_length, ncol = affected_samples)
    diff_hit <- rep(0, template_length)

    for (rep_i in seq_len(pilot_reps)) {
        beta_sim <- matrix(NA_real_, nrow = template_length, ncol = affected_samples)
        for (sample_i in seq_len(affected_samples)) {
            new_prob <- .simulationShiftedProbabilities(
                base_prob = base_prob[, sample_i],
                diff_hit = diff_hit,
                corr_sd = corr_sd,
                neighbor_window = neighbor_window
            )
            beta_sim[, sample_i] <- stats::rbinom(
                n = template_length,
                size = template_cov,
                prob = new_prob
            ) / template_cov
        }
        m_values <- .transformBeta(
            beta_sim,
            pheno = data.frame(sample = seq_len(affected_samples))
        )
        pair_corr <- .simulationComputePairCorrelations(
            x = m_values[-nrow(m_values), , drop = FALSE],
            y = m_values[-1L, , drop = FALSE]
        )
        pair_corr <- pair_corr[pair_corr > 0]
        rep_metrics[rep_i] <- if (length(pair_corr) == 0L) 0 else mean(pair_corr)
    }

    mean(rep_metrics)
}

.simulationBuildCorrelationLookup <- function(affected_samples,
                                              template_length,
                                              template_cov,
                                              neighbor_window = 5L,
                                              corr_sd_grid = seq(0.1, 3.0, by = 0.1)) {
    if (affected_samples < 2L || template_length < 2L) {
        return(data.frame(corr_sd = 0.30, metric = 0))
    }

    withr::with_seed(1, {
        data.frame(
            corr_sd = corr_sd_grid,
            metric = vapply(
                corr_sd_grid,
                .simulationCorrelationMetric,
                numeric(1),
                affected_samples = affected_samples,
                template_length = template_length,
                template_cov = template_cov,
                neighbor_window = neighbor_window
            )
        )
    })
}

.simulationPickCorrelationIndex <- function(target, lookup, default_corr_sd = 0.30) {
    if (is.null(lookup) || nrow(lookup) == 0L) {
        return(1L)
    }
    valid_sd <- is.finite(lookup$corr_sd)
    valid_metric <- valid_sd & is.finite(lookup$metric)
    if (!any(valid_metric)) {
        if (any(valid_sd)) {
            return(which(valid_sd)[which.min(abs(lookup$corr_sd[valid_sd] - default_corr_sd))])
        }
        return(1L)
    }
    valid_idx <- which(valid_metric)
    if (!is.finite(target)) {
        return(valid_idx[which.min(abs(lookup$corr_sd[valid_idx] - default_corr_sd))])
    }
    valid_idx[which.min(abs(lookup$metric[valid_idx] - target))]
}

.simulationPickCorrelationSd <- function(target, lookup, default_corr_sd = 0.30) {
    if (is.null(lookup) || nrow(lookup) == 0L) {
        return(default_corr_sd)
    }
    lookup$corr_sd[[.simulationPickCorrelationIndex(
        target = target,
        lookup = lookup,
        default_corr_sd = default_corr_sd
    )]]
}

.simulationTemplateLength <- function(indices, min_len = 5L) {
    segment_lengths <- lengths(indices)
    max(min_len, as.integer(round(stats::median(segment_lengths))))
}

.simulationTemplateCoverage <- function(cov) {
    template_cov <- stats::median(cov[cov > 0], na.rm = TRUE)
    if (!is.finite(template_cov) || template_cov < 1) {
        template_cov <- 100
    }
    as.integer(round(template_cov))
}

.convertCountsToBeta <- function(meth, cov) {
    beta <- (meth + 0.5) / (cov + 1)
    beta[cov <= 0] <- NA_real_
    beta
}

.convertCountsToLogits <- function(meth, cov) {
    stats::qlogis(.clampSimulationBeta(.convertCountsToBeta(meth, cov)))
}

.clampSimulationBeta <- function(x) {
    x_dim <- dim(x)
    x_dimnames <- dimnames(x)
    out <- pmin(pmax(x, 1e-6), 1 - 1e-6)
    if (!is.null(x_dim)) {
        dim(out) <- x_dim
        dimnames(out) <- x_dimnames
    }
    out
}

.simulationCountsFromEta <- function(eta, cov, resample_counts) {
    prob <- plogis(eta)
    prob[!is.finite(prob)] <- 0.5
    cov <- round(cov)
    cov[cov < 0] <- 0
    if (isTRUE(resample_counts)) {
        out <- matrix(
            stats::rbinom(length(cov), size = c(cov), prob = c(prob)),
            nrow = nrow(cov),
            ncol = ncol(cov)
        )
    } else {
        out <- round(cov * prob)
    }
    out[out < 0] <- 0
    out_over_cov <- out > cov
    out[out_over_cov] <- cov[out_over_cov]
    out
}

